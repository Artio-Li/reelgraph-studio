/** 把结构化维度拼成一句可直接喂给模型的风格基线 */
export function composeStylePrompt(preset) {
  if (!preset) return '';
  return [
    preset.camera,
    preset.lighting,
    preset.color,
    preset.texture,
    preset.composition,
    preset.motion,
  ].filter(Boolean).join('；');
}

export const STYLE_PRESETS = PRESETS.map((preset) => ({
  ...preset,
  prompt: composeStylePrompt(preset),
}));

export function getStylePreset(id) {
  const key = String(id || '').trim();
  if (!key) return null;
  return STYLE_PRESETS.find((item) => item.id === key) || null;
}

/** Planner 用的分维度基线，比整句更利于模型按维度落笔 */
export function styleBaseline(preset) {
  if (!preset) return '';
  return [
    '风格基线（所有镜头必须遵守）：',
    `- 机身与镜头：${preset.camera}`,
    `- 光线方案：${preset.lighting}`,
    `- 调色：${preset.color}`,
    `- 质感：${preset.texture}`,
    `- 构图与运镜：${preset.composition}`,
    `- 节奏：${preset.motion}`,
  ].join('\n');
}
